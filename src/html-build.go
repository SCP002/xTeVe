package src

import (
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var htmlFolder string
var goFile string
var mapName string
var packageName string

var blankMap = make(map[string]string)

// HTMLInit : Define file paths
// mapName = Name of the map to be created
// htmlFolder: HTML Files Folder
// packageName: Name of the package
func HTMLInit(name, pkg, folder, file string) {
	htmlFolder = folder
	goFile = file
	mapName = name
	packageName = pkg
}

// BuildGoFile : Creates the GO Document
func BuildGoFile() error {
	var err = checkHTMLFile(htmlFolder)

	if err != nil {
		return err
	}

	var content string
	content += "// Code generated by xteve -dev from the html folder. DO NOT EDIT.\n\n"
	content += `package ` + packageName + "\n\n"
	content += `var ` + mapName + ` = make(map[string]string)` + "\n\n"
	content += "func loadHTMLMap() {" + "\n\n"

	files, err := createMapFromFiles(htmlFolder)
	if err != nil {
		return err
	}

	content += files + "\n"

	content += "}" + "\n\n"
	return writeStringToFile(goFile, content)
}

// GetHTMLString : base64 -> string
func GetHTMLString(base string) string {
	content, err := base64.StdEncoding.DecodeString(base)
	if err != nil {
		ShowError(err, 0)
	}
	return string(content)
}

func createMapFromFiles(folder string) (string, error) {
	var path = getLocalPath(folder)

	if err := filepath.Walk(path, readFilesToMap); err != nil {
		return "", err
	}

	var content strings.Builder

	// Sort map keys before writing to file to prevent git mark webUI.go as modified when no real changes has been made
	keys := make([]string, 0, len(blankMap))
	for k := range blankMap {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, key := range keys {
		var newKey = key
		fmt.Fprintf(&content, "  %s[\"%s\"] = \"%s\"\n", mapName, newKey, blankMap[key])
	}

	return content.String(), nil
}

func readFilesToMap(path string, info os.FileInfo, err error) error {
	if err != nil {
		return err
	}

	if !info.IsDir() {
		base64Str, err := fileToBase64(getLocalPath(path))
		if err != nil {
			return err
		}
		blankMap[filepath.ToSlash(path)] = base64Str
	}

	return nil
}

func fileToBase64(file string) (string, error) {
	buf, err := os.ReadFile(file)
	if err != nil {
		return "", err
	}

	return base64.StdEncoding.EncodeToString(buf), nil
}

func getLocalPath(filename string) string {
	path, file := filepath.Split(filename)
	var newPath = filepath.ToSlash(filepath.Dir(path))

	var newFileName = newPath + "/" + file

	return newFileName
}

func writeStringToFile(filename, content string) error {
	return os.WriteFile(getPlatformFile(filename), []byte(content), 0644)
}

func checkHTMLFile(filename string) error {
	_, err := os.Stat(getLocalPath(filename))
	return err
}
